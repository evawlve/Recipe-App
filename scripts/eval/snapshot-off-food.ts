/**
 * snapshot-off-food.ts — per-row-restorable snapshot of the ENTIRE "OffFood"
 * table, taken on the DATABASE HOST so it survives dev-machine reboots.
 *
 * This is the hard prerequisite (and the ONLY rollback path) for the §4
 * divided-panel corpus repair, which multiplies numeric panel fields by
 * servingGrams/100 on ~3,173 rows — a wrong flag there inflates a 1,060 g row
 * by 10.6x, so the snapshot must exist BEFORE any repair write is even
 * dry-run-approved. See scripts/eval/detect-panel-scale-divided.ts and
 * sync-docs/mapping_investigation_playbook.md §3/§11.
 *
 * ===========================================================================
 * HOW IT RUNS
 * ===========================================================================
 * Designed to be INVOKED FROM A DEV MACHINE. Every remote operation goes over
 * one ssh channel to the database host; the dump itself is produced entirely
 * ON THE HOST (docker exec psql COPY ... TO STDOUT | gzip > file) and LANDS ON
 * THE HOST under --out-dir, so a dev-machine reboot or dropped ssh session
 * cannot destroy the rollback path. Only counts, checksums and column lists
 * ever cross back over ssh.
 *
 *   npx ts-node --project tsconfig.scripts.json --transpile-only \
 *     -r tsconfig-paths/register scripts/eval/snapshot-off-food.ts [flags]
 *
 * Flags (env fallback in parens, defaults match the documented topology):
 *   --host <ssh host>        (SNAPSHOT_SSH_HOST,      default owner@192.168.1.133)
 *   --container <name>       (SNAPSHOT_DB_CONTAINER,  default mealspire-db)
 *   --out-dir <dir on host>  (SNAPSHOT_OUT_DIR,       default /home/owner/snapshots)
 *   --db-user <user>         (SNAPSHOT_DB_USER, else DATABASE_URL user, else postgres)
 *   --db-name <name>         (SNAPSHOT_DB_NAME, else DATABASE_URL db,   else postgres)
 *   --exclude-embedding      omit the vector(384) "embedding" column (see below)
 *   --label <suffix>         extra token in the output filename
 *   --measure                READ-ONLY size report; dumps nothing (see below)
 *
 * ===========================================================================
 * WHY COPY TEXT FORMAT, NOT pg_dump -t
 * ===========================================================================
 * Nothing in this repo snapshots OffFood today — `grep -rn pg_dump` finds only
 * a comment telling a human to do it by hand. The choice here is deliberate:
 *
 * 1. PER-ROW RESTORE is the requirement. The §4 repair may be PARTIALLY rolled
 *    back (the plausibility guard refuses some rows; a hand audit may refute
 *    others). A pg_dump archive restores a whole table; restoring one row from
 *    it means loading it somewhere else anyway. COPY text loads into a side
 *    table, and rollback is `UPDATE "OffFood" ... FROM side WHERE barcode = ...`
 *    for exactly the rows you name.
 * 2. VERIFIABILITY (playbook §11 class B — absence must never read as a PASS).
 *    COPY text emits EXACTLY one line per row (embedded newlines are escaped
 *    as \n), so `gzip -dc | wc -l` must equal a SELECT count(*) taken in the
 *    same run. pg_dump's SQL stream has no invariant this mechanical — you
 *    cannot fail-closed on "the dump silently stopped early" without parsing
 *    SQL. This script verifies count-before == dump lines == count-after and
 *    refuses the snapshot otherwise.
 * 3. EXPLICIT COLUMN COVERAGE. The SELECT lists every column discovered live
 *    from information_schema at dump time (a column added by a future
 *    migration is included automatically), and the discovered set must be a
 *    superset of REQUIRED_COLUMNS — every column the §4 repair could write
 *    (nutrientsPer100g; corruptReason via the mark stage; updatedAt) plus the
 *    full remaining row so an unintended write to ANY column is recoverable.
 *    pg_dump's coverage is implicit; you cannot fail-closed on a missing column.
 *
 * ===========================================================================
 * THE embedding COLUMN — the one genuine size question
 * ===========================================================================
 * "embedding vector(384)" is not writable by the repair, is regenerated by the
 * auto-embed pipeline, and its text rendering may dominate the dump size on a
 * ~1M-row table. Whether excluding it is worth it hinges on LIVE size numbers
 * this offline session cannot take:
 *   UNSETTLED: actual OffFood dump size / embedding share — needs the
 *   authorized run. Take it with --measure (read-only) first.
 * The DEFAULT is the safe complete choice: ALL columns, embedding included.
 * Pass --exclude-embedding only after --measure shows it is both dominant and
 * a problem for the host's disk or the dump window.
 *
 * ===========================================================================
 * FAIL-CLOSED CONTRACT (playbook §11 class B)
 * ===========================================================================
 * Every step returns a nonzero exit with an explicit expected-vs-observed
 * message on: ssh/transport failure, docker/psql/COPY failure, count mismatch,
 * count that will not parse (empty stdout is NOT zero), empty table, empty or
 * truncated dump, gzip corruption, column-count drift, pre-existing output
 * file (refuse-overwrite), mv/manifest failure. The dump is written to a
 * .partial name and only renamed to its final name AFTER every verification
 * passes — a file with the final name IS a verified snapshot, always.
 * Fail-injection tests: scripts/eval/__tests__/snapshot-off-food.test.ts.
 *
 * ===========================================================================
 * RESTORE SEMANTICS (also printed after every successful run + manifest)
 * ===========================================================================
 * The snapshot loads into a SIDE table, never directly into "OffFood"; chosen
 * rows are then restored with UPDATE ... FROM joined on barcode. UPDATE cannot
 * resurrect a DELETED row — the §4 repair only UPDATEs, so that is out of
 * scope, but a full-column snapshot also supports INSERT ... WHERE NOT EXISTS
 * for resurrection if some other operation deletes rows.
 *
 * READ-ONLY toward the database in every mode (COPY TO STDOUT + SELECTs); the
 * only things written are the snapshot + manifest files on the host.
 * There is no --execute path in this file.
 */

