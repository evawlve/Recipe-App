/** Parse DATABASE_URL for user/dbname WITHOUT ever printing it (it carries a
 *  password). Returns nulls when absent or malformed. */
export function dbIdentityFromEnv(env: NodeJS.ProcessEnv): { user: string | null; db: string | null } {
    const url = env.DATABASE_URL;
    if (!url) return { user: null, db: null };
    try {
        const u = new URL(url);
        const db = u.pathname.replace(/^\//, '').split('?')[0];
        return { user: u.username ? decodeURIComponent(u.username) : null, db: db || null };
    } catch {
        return { user: null, db: null };
    }
}

export function parseCliArgs(argv: string[], env: NodeJS.ProcessEnv): { config: SnapshotConfig } | { error: string } {
    const ident = dbIdentityFromEnv(env);
    const cfg: SnapshotConfig = {
        sshHost: env.SNAPSHOT_SSH_HOST || DEFAULT_SSH_HOST,
        container: env.SNAPSHOT_DB_CONTAINER || DEFAULT_CONTAINER,
        outDir: env.SNAPSHOT_OUT_DIR || DEFAULT_OUT_DIR,
        dbUser: env.SNAPSHOT_DB_USER || ident.user || 'postgres',
        dbName: env.SNAPSHOT_DB_NAME || ident.db || 'postgres',
        excludeEmbedding: false,
        measure: false,
        label: null,
    };
    const takesValue: Record<string, (v: string) => void> = {
        '--host': v => { cfg.sshHost = v; },
        '--container': v => { cfg.container = v; },
        '--out-dir': v => { cfg.outDir = v; },
        '--db-user': v => { cfg.dbUser = v; },
        '--db-name': v => { cfg.dbName = v; },
        '--label': v => { cfg.label = v; },
    };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--exclude-embedding') { cfg.excludeEmbedding = true; continue; }
        if (a === '--measure') { cfg.measure = true; continue; }
        if (a in takesValue) {
            const v = argv[i + 1];
            if (v === undefined || v.startsWith('--')) return { error: `${a} requires a value` };
            takesValue[a](v);
            i++;
            continue;
        }
        // Unknown flags REFUSE (a typo'd --exclude-embeding silently ignored
        // would dump the wrong shape and report success).
        return { error: `unknown argument: ${a}` };
    }
    if (cfg.label !== null && !/^[A-Za-z0-9_-]+$/.test(cfg.label)) {
        return { error: `--label must match [A-Za-z0-9_-]+ (it lands in a filename)` };
    }
    return { config: cfg };
}

async function main(): Promise<void> {
    // Load .env for DATABASE_URL identity fallback only; never printed.
    try {
        // eslint-disable-next-line @typescript-eslint/no-require-imports
        require('dotenv').config({ quiet: true });
    } catch { /* dotenv is optional here; flags/env still work */ }

    const args = process.argv.slice(2);
    if (args.includes('--help') || args.includes('-h')) {
        console.log(USAGE);
        return;
    }
    const parsed = parseCliArgs(args, process.env);
    if ('error' in parsed) {
        console.error(parsed.error);
        console.error(USAGE);
        process.exitCode = 1;
        return;
    }
    const cfg = parsed.config;
    const t = sshTransport(cfg.sshHost);
    console.log(`[target] host=${cfg.sshHost} container=${cfg.container} db=${cfg.dbName} out=${cfg.outDir}${cfg.measure ? ' (MEASURE ONLY)' : ''}`);
    const code = cfg.measure ? await measure(cfg, t) : await snapshot(cfg, t);
    process.exitCode = code;
}

if (require.main === module) {
    main().catch(err => { console.error(err); process.exit(2); });
}
