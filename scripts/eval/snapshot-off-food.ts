/** POSIX single-quote wrapping; the only metacharacter inside single quotes
 *  is the single quote itself. */
export function shellQuote(s: string): string {
    return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** Strict count parse: ONLY an all-digit string is a number. Empty stdout,
 *  psql banners, error text — all parse to null, never to 0 (§11 class B:
 *  the absence of a count must not read as a count of zero). */
export function parseCount(stdout: string): number | null {
    const t = stdout.trim();
    return /^\d+$/.test(t) ? Number(t) : null;
}

/** Column names are interpolated into SQL as quoted identifiers; refuse
 *  anything that could escape the quoting rather than trying to be clever. */
export function isSafeColumnName(name: string): boolean {
    return /^[A-Za-z_][A-Za-z0-9_]*$/.test(name);
}

export function quoteIdent(name: string): string {
    return `"${name}"`;
}

/** The dump statement. ORDER BY barcode makes output deterministic and
 *  snapshot-to-snapshot diffable. */
export function buildCopySql(columns: string[]): string {
    const cols = columns.map(quoteIdent).join(',');
    return `COPY (SELECT ${cols} FROM "${TABLE}" ORDER BY "barcode") TO STDOUT`;
}

export function timestampToken(now: Date): string {
    return now.toISOString().replace(/\.\d{3}Z$/, 'Z').replace(/:/g, '-');
}

export interface SnapshotPaths {
    dataFile: string;
    partialFile: string;
    metaFile: string;
}

export function snapshotPaths(cfg: SnapshotConfig): SnapshotPaths {
    const ts = timestampToken(cfg.now ?? new Date());
    const label = cfg.label ? `-${cfg.label}` : '';
    const embed = cfg.excludeEmbedding ? '-noembed' : '';
    const base = `${cfg.outDir}/${TABLE}-${ts}${label}${embed}`;
    return {
        dataFile: `${base}.tsv.gz`,
        partialFile: `${base}.tsv.gz.partial`,
        metaFile: `${base}.meta.json`,
    };
}

/** `docker exec <container> psql ...` fragment shared by every SQL step.
 *  -X skips psqlrc (no banner noise), ON_ERROR_STOP makes SQL errors exit
 *  nonzero instead of printing-and-continuing. */
export function psqlCommand(cfg: SnapshotConfig, sql: string): string {
    return [
        'docker exec', shellQuote(cfg.container),
        'psql', '-X', '-v', 'ON_ERROR_STOP=1',
        '-U', shellQuote(cfg.dbUser),
        '-d', shellQuote(cfg.dbName),
        '-A', '-t', '-c', shellQuote(sql),
    ].join(' ');
}

/** Parse `KEY=value` lines from the verify step; a missing or duplicated key
 *  is a hard failure at the call site (returns null). */
export function parseLabeled(stdout: string, keys: string[]): Record<string, string> | null {
    const out: Record<string, string> = {};
    for (const line of stdout.split('\n')) {
        const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
        if (!m) continue;
        if (m[1] in out) return null; // duplicate label — ambiguous, refuse
        out[m[1]] = m[2];
    }
    for (const k of keys) {
        if (!(k in out)) return null;
    }
    return out;
}

/** The exact per-row restore recipe, printed on success and stored in the
 *  manifest. `columns` is the DUMPED list — restore must never touch a column
 *  the snapshot does not carry. */
export function restoreInstructions(cfg: SnapshotConfig, paths: SnapshotPaths, columns: string[], rowCount: number): string[] {
    const colList = columns.map(quoteIdent).join(',');
    const setList = columns
        .filter(c => c !== 'barcode')
        .map(c => `${quoteIdent(c)}=s.${quoteIdent(c)}`)
        .join(', ');
    const psql = `docker exec -i ${cfg.container} psql -X -v ON_ERROR_STOP=1 -U ${cfg.dbUser} -d ${cfg.dbName}`;
    return [
        `# PER-ROW RESTORE — run ON THE DB HOST (${cfg.sshHost}). The snapshot loads`,
        `# into a SIDE table; never COPY into "${TABLE}" directly.`,
        `# 1. side table (column-identical to ${TABLE}, no data):`,
        `${psql} -c 'CREATE TABLE "${TABLE}_restore" (LIKE "${TABLE}")'`,
        `# 2. load the snapshot:`,
        `gzip -dc ${paths.dataFile} | ${psql} -c 'COPY "${TABLE}_restore"(${colList}) FROM STDIN'`,
        `# 3. sanity — MUST print ${rowCount}:`,
        `${psql} -Atc 'SELECT count(*) FROM "${TABLE}_restore"'`,
        `# 4. roll back CHOSEN rows (edit the barcode list; drop the AND clause only`,
        `#    for a deliberate full-table rollback):`,
        `${psql} -c 'UPDATE "${TABLE}" f SET ${setList} FROM "${TABLE}_restore" s WHERE f."barcode"=s."barcode" AND f."barcode" = ANY(ARRAY[$$BARCODE1$$,$$BARCODE2$$])'`,
        `# 5. UPDATE cannot resurrect DELETED rows (the §4 repair only UPDATEs). If an`,
        `#    operation deleted rows, resurrect from a FULL-column snapshot with:`,
        `#    INSERT INTO "${TABLE}"(${colList}) SELECT ${colList} FROM "${TABLE}_restore" s`,
        `#      WHERE NOT EXISTS (SELECT 1 FROM "${TABLE}" f WHERE f."barcode"=s."barcode")`,
        `# 6. when verified: ${psql} -c 'DROP TABLE "${TABLE}_restore"'`,
    ];
}

// ===========================================================================
// Failure plumbing — every refusal goes through here so the message shape
// (step, expected, observed) is uniform and grep-able.
// ===========================================================================

class StepFailure extends Error {
    constructor(step: string, expected: string, observed: string) {
        super(`[${step}] FAIL — expected: ${expected}; observed: ${observed}`);
        this.name = 'StepFailure';
    }
}

async function runStep(t: Transport, step: string, script: string): Promise<ExecResult> {
    const res = await t.exec(step, script);
    if (res.code !== 0) {
        throw new StepFailure(
            step,
            'exit 0 from the remote command',
            `exit ${res.code}; stderr: ${res.stderr.trim().slice(0, 500) || '(empty)'}`,
        );
    }
    return res;
}

// ===========================================================================
// The snapshot pipeline
// ===========================================================================

export async function discoverColumns(cfg: SnapshotConfig, t: Transport): Promise<string[]> {
    const sql = `SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='${TABLE}' ORDER BY ordinal_position`;
    const res = await runStep(t, 'discover-columns', psqlCommand(cfg, sql));
    const cols = res.stdout.split('\n').map(l => l.trim()).filter(l => l.length > 0);
    if (cols.length === 0) {
        throw new StepFailure('discover-columns', `>= 1 column for table "${TABLE}"`, 'zero columns (table missing, or psql emitted nothing)');
    }
    for (const c of cols) {
        if (!isSafeColumnName(c)) {
            throw new StepFailure('discover-columns', 'column names matching [A-Za-z_][A-Za-z0-9_]*', `unsafe column name ${JSON.stringify(c)}`);
        }
    }
    const missing = REQUIRED_COLUMNS.filter(rc => !cols.includes(rc));
    if (missing.length > 0) {
        throw new StepFailure(
            'discover-columns',
            `all REQUIRED_COLUMNS present (the §4 repair's writable set)`,
            `missing: ${missing.join(', ')} — if a migration renamed/dropped these, update REQUIRED_COLUMNS deliberately`,
        );
    }
    return cfg.excludeEmbedding ? cols.filter(c => c !== 'embedding') : cols;
}

async function selectCount(cfg: SnapshotConfig, t: Transport, step: string): Promise<number> {
    const res = await runStep(t, step, psqlCommand(cfg, `SELECT count(*) FROM "${TABLE}"`));
    const n = parseCount(res.stdout);
    if (n === null) {
        throw new StepFailure(step, 'an all-digit row count on stdout', `unparseable ${JSON.stringify(res.stdout.trim().slice(0, 200))} (empty/garbage is NOT zero)`);
    }
    return n;
}

export async function snapshot(cfg: SnapshotConfig, t: Transport, log: (s: string) => void = console.log): Promise<number> {
    const paths = snapshotPaths(cfg);
    try {
        // 0. transport sanity — the cheapest possible remote no-op, so a dead
        //    host/key fails here with an unambiguous message, not mid-dump.
        const hello = await runStep(t, 'transport-preflight', 'echo SNAPSHOT_TRANSPORT_OK');
        if (hello.stdout.trim() !== 'SNAPSHOT_TRANSPORT_OK') {
            throw new StepFailure('transport-preflight', 'SNAPSHOT_TRANSPORT_OK', JSON.stringify(hello.stdout.trim().slice(0, 200)));
        }

        // 1. output dir exists on the HOST.
        await runStep(t, 'mkdir', `mkdir -p ${shellQuote(cfg.outDir)} && test -d ${shellQuote(cfg.outDir)}`);

        // 2. refuse to overwrite. Exit code stays 0 both ways so a transport
        //    failure is never mistaken for absence; the VERDICT is parsed, and
        //    an unrecognized verdict refuses (class B).
        const probe = await runStep(
            t,
            'refuse-overwrite',
            `if [ -e ${shellQuote(paths.dataFile)} ] || [ -e ${shellQuote(paths.partialFile)} ] || [ -e ${shellQuote(paths.metaFile)} ]; then echo EXISTS; else echo ABSENT; fi`,
        );
        const verdict = probe.stdout.trim();
        if (verdict === 'EXISTS') {
            throw new StepFailure('refuse-overwrite', `no file at ${paths.dataFile} (nor .partial/.meta.json)`, 'a file already exists — this script never overwrites a snapshot; pick a new --label or move the old file');
        }
        if (verdict !== 'ABSENT') {
            throw new StepFailure('refuse-overwrite', `verdict EXISTS or ABSENT`, JSON.stringify(verdict.slice(0, 200)));
        }

        // 3. columns, live from information_schema, pinned-superset-checked.
        const columns = await discoverColumns(cfg, t);
        log(`[columns] ${columns.length} columns${cfg.excludeEmbedding ? ' (embedding EXCLUDED by flag)' : ''}: ${columns.join(', ')}`);

        // 4. count in the same run — this is what the dump must reproduce.
        const countBefore = await selectCount(cfg, t, 'count-before');
        if (countBefore === 0) {
            throw new StepFailure('count-before', `a non-empty "${TABLE}" (~1M rows in the documented topology)`, 'count(*) = 0 — snapshotting an empty table as a rollback path would be fail-open; refusing');
        }
        log(`[count-before] ${countBefore} rows`);

        // 5. the dump, entirely host-side, into the .partial name.
        const dumpScript = [
            'set -euo pipefail',
            `${psqlCommand(cfg, buildCopySql(columns))} | gzip -9 > ${shellQuote(paths.partialFile)}`,
        ].join('; ');
        await runStep(t, 'dump', dumpScript);
        log(`[dump] COPY stream written to ${paths.partialFile}`);

        // 6. integrity: gzip self-check, then one full decompress pass that
        //    counts lines AND first-row fields (no head/SIGPIPE games), plus
        //    size + sha256 for the manifest.
        const verifyScript = [
            'set -euo pipefail',
            `gzip -t ${shellQuote(paths.partialFile)}`,
            `gzip -dc ${shellQuote(paths.partialFile)} | awk -F'\\t' 'NR==1{nf=NF} END{printf "LINES=%d\\nCOLS=%d\\n", NR, nf}'`,
            `printf 'BYTES=%s\\n' "$(stat -c %s ${shellQuote(paths.partialFile)})"`,
            `printf 'SHA256=%s\\n' "$(sha256sum ${shellQuote(paths.partialFile)} | awk '{print $1}')"`,
        ].join('; ');
        const verify = await runStep(t, 'verify-integrity', verifyScript);
        const labels = parseLabeled(verify.stdout, ['LINES', 'COLS', 'BYTES', 'SHA256']);
        if (labels === null) {
            throw new StepFailure('verify-integrity', 'LINES=/COLS=/BYTES=/SHA256= exactly once each', JSON.stringify(verify.stdout.trim().slice(0, 300)));
        }
        const lines = parseCount(labels.LINES);
        const cols = parseCount(labels.COLS);
        const bytes = parseCount(labels.BYTES);
        if (lines === null || cols === null || bytes === null) {
            throw new StepFailure('verify-integrity', 'numeric LINES/COLS/BYTES', JSON.stringify(verify.stdout.trim().slice(0, 300)));
        }
        if (lines === 0) {
            throw new StepFailure('verify-integrity', `${countBefore} data lines`, 'an EMPTY dump file — the COPY produced no rows');
        }
        if (lines !== countBefore) {
            throw new StepFailure('verify-integrity', `${countBefore} lines (count-before)`, `${lines} lines in the dump — truncated or the table moved; refusing`);
        }
        if (cols !== columns.length) {
            throw new StepFailure('verify-integrity', `${columns.length} tab-separated fields on row 1`, `${cols} — dump shape does not match the column list; refusing`);
        }

        // 7. count again: if the table moved DURING the run the snapshot is
        //    still internally consistent (COPY reads one MVCC snapshot) but
        //    its claim to represent "the table as of this run" is void — and
        //    the §4 repair must not proceed on a moving table anyway.
        const countAfter = await selectCount(cfg, t, 'count-after');
        if (countAfter !== countBefore) {
            throw new StepFailure('count-after', `${countBefore} rows (unchanged during the dump)`, `${countAfter} — "${TABLE}" moved during the snapshot; re-run when nothing is writing`);
        }

        // 8. only now does the final name come into existence.
        await runStep(t, 'finalize', `mv ${shellQuote(paths.partialFile)} ${shellQuote(paths.dataFile)}`);

        // 9. manifest, next to the data file.
        const restore = restoreInstructions(cfg, paths, columns, countBefore);
        const manifest = {
            table: TABLE,
            createdAt: (cfg.now ?? new Date()).toISOString(),
            sshHost: cfg.sshHost,
            container: cfg.container,
            dbName: cfg.dbName,
            dbUser: cfg.dbUser,
            file: paths.dataFile,
            format: 'postgres COPY text (tab-delimited, \\N nulls, one line per row), gzip',
            rowCount: countBefore,
            columnCount: columns.length,
            columns,
            excludeEmbedding: cfg.excludeEmbedding,
            gzipBytes: bytes,
            sha256: labels.SHA256,
            restore,
        };
        const metaScript = `printf '%s\\n' ${shellQuote(JSON.stringify(manifest, null, 2))} > ${shellQuote(paths.metaFile)}`;
        try {
            await runStep(t, 'manifest', metaScript);
        } catch (err) {
            // The verified data file already exists under its final name; say
            // so explicitly, but a snapshot without its manifest is NOT a
            // success.
            throw new StepFailure(
                'manifest',
                `manifest written to ${paths.metaFile}`,
                `${err instanceof Error ? err.message : String(err)} — NOTE the verified data file DOES exist at ${paths.dataFile}`,
            );
        }

        log('');
        log(`SNAPSHOT OK — ${countBefore} rows x ${columns.length} columns, ${bytes} bytes gzipped`);
        log(`  data:     ${paths.dataFile}`);
        log(`  manifest: ${paths.metaFile}`);
        log(`  sha256:   ${labels.SHA256}`);
        log('');
        for (const line of restore) log(line);
        return 0;
    } catch (err) {
        if (err instanceof StepFailure) {
            log(err.message);
            log(`SNAPSHOT REFUSED — nothing at ${paths.dataFile} is trustworthy unless the file exists under its FINAL name (partials are unverified).`);
            return 1;
        }
        throw err;
    }
}

// ===========================================================================
// --measure: the read-only size report that settles the embedding question
// ===========================================================================

export async function measure(cfg: SnapshotConfig, t: Transport, log: (s: string) => void = console.log): Promise<number> {
    const sql =
        `SELECT count(*), pg_total_relation_size('"${TABLE}"'), pg_relation_size('"${TABLE}"'), COALESCE(sum(pg_column_size(embedding)),0) FROM "${TABLE}"`;
    try {
        const res = await runStep(t, 'measure', psqlCommand(cfg, sql));
        const parts = res.stdout.trim().split('|').map(p => parseCount(p));
        if (parts.length !== 4 || parts.some(p => p === null)) {
            throw new StepFailure('measure', 'four |-separated integers (rows, total, heap, embedding bytes)', JSON.stringify(res.stdout.trim().slice(0, 200)));
        }
        const [rows, totalBytes, heapBytes, embeddingBytes] = parts as number[];
        const mb = (b: number) => (b / (1024 * 1024)).toFixed(1);
        log(`[measure] "${TABLE}" (read-only; nothing dumped):`);
        log(`  rows:                    ${rows}`);
        log(`  total relation size:     ${mb(totalBytes)} MB (heap+indexes+toast)`);
        log(`  heap size:               ${mb(heapBytes)} MB`);
        log(`  embedding column bytes:  ${mb(embeddingBytes)} MB (in-tuple; text rendering in the dump is LARGER)`);
        log(`  everything-but-embedding is roughly heap - embedding = ${mb(Math.max(heapBytes - embeddingBytes, 0))} MB`);
        log('');
        log('Decision rule: the DEFAULT dump includes ALL columns (safe complete choice).');
        log('Only if the embedding share makes the dump impractical for the host disk or');
        log('the dump window, re-run the snapshot with --exclude-embedding (embedding is');
        log('not writable by the §4 repair and regenerates via the auto-embed pipeline).');
        return 0;
    } catch (err) {
        if (err instanceof StepFailure) {
            log(err.message);
            return 1;
        }
        throw err;
    }
}

